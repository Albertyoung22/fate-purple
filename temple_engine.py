def toss_moon_blocks():
    """
    模擬擲筊 (Moon Blocks / Bwa Bwei):
    一陽一陰 = 聖筊 (Sheng Bwei, 神明允諾 / 大吉) - 機率 50%
    雙陽 (平面朝上) = 笑筊 (Xiao Bwei, 神明微笑 / 緣主已知答案或心意未定) - 機率 25%
    雙陰 (凸面朝上) = 陰筊/怒筊 (Yin Bwei, 神明不允 / 時機不對) - 機率 25%
    """
    block1 = random.choice(["陽", "陰"]) # 陽=平, 陰=凸
    block2 = random.choice(["陽", "陰"])
    
    if (block1 == "陽" and block2 == "陰") or (block1 == "陰" and block2 == "陽"):
        result_type = "sheng"
        name = "聖筊（一陽一陰）"
        description = "神明允諾，大吉感應！此籤確為神明所賜，請誠心參悟籤詩聖意。"
        is_confirmed = True
    elif block1 == "陽" and block2 == "陽":
        result_type = "xiao"
        name = "笑筊（雙陽面朝上）"
        description = "神明微笑不言，或緣主心中已有定見、亦或提問不夠明確。請放鬆心神，誠心再次請示。"
        is_confirmed = False
    else:
        result_type = "yin"
        name = "陰筊（雙陰面朝上）"
        description = "神明示警或時機未至，此籤未獲首肯。請稍作沉澱，重新稟明心願後再次求籤。"
        is_confirmed = False
        
    return {
        "block1": block1,
        "block2": block2,
        "result_type": result_type,
        "name": name,
        "description": description,
        "is_confirmed": is_confirmed
    }

