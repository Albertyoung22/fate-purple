def cast_iching_hexagram(question="心念所求", seed_val=None):
    """
    執行易經六爻靈動起卦 (模擬三枚乾隆古錢搖卦)
    三枚古錢 (字=2, 紋=3):
    - 6: 老陰 (--x--) -> 變少陽 (-------)
    - 7: 少陽 (-------) 不變
    - 8: 少陰 (-- --) 不變
    - 9: 老陽 (---o---) 變少陰 (-- --)
    """
    if seed_val is None:
        seed_val = int(time.time() * 1000) + sum(ord(c) for c in question)
    rng = random.Random(seed_val)
    
    # 擲六次銅錢，由下而上 (初爻到上爻)
    lines_val = []
    original_bits = []
    changed_bits = []
    changing_lines = []
    
    for i in range(6):
        # 三枚銅錢
        coins = [rng.choice([2, 3]) for _ in range(3)]
        total = sum(coins)
        lines_val.append(total)
        
        # 本爻
        if total in (7, 9): # 陽爻
            original_bits.append(1)
        else: # 陰爻
            original_bits.append(0)
            
        # 變爻
        if total == 9: # 老陽變陰
            changed_bits.append(0)
            changing_lines.append(i + 1)
        elif total == 6: # 老陰變陽
            changed_bits.append(1)
            changing_lines.append(i + 1)
        elif total == 7: # 少陽不變
            changed_bits.append(1)
        else: # 少陰不變
            changed_bits.append(0)

    # 上卦與下卦 (0,1,2 為下卦; 3,4,5 為上卦)
    lower_orig_tuple = tuple(original_bits[0:3])
    upper_orig_tuple = tuple(original_bits[3:6])
    lower_orig_name, lower_orig_nature, lower_orig_sym = BAGUA[lower_orig_tuple]
    upper_orig_name, upper_orig_nature, upper_orig_sym = BAGUA[upper_orig_tuple]
    
    # 本卦資訊
    orig_key = (upper_orig_name, lower_orig_name)
    orig_info = HEXAGRAMS.get(orig_key, ("易經古卦", "䷀", "平", "天道運行", "順勢而為", "靜心觀察"))
    
    # 變卦
    lower_chg_tuple = tuple(changed_bits[0:3])
    upper_chg_tuple = tuple(changed_bits[3:6])
    lower_chg_name, _, _ = BAGUA[lower_chg_tuple]
    upper_chg_name, _, _ = BAGUA[upper_chg_tuple]
    chg_key = (upper_chg_name, lower_chg_name)
    chg_info = HEXAGRAMS.get(chg_key, orig_info)
    
    # 互卦 (2,3,4 為下互; 3,4,5 為上互)
    lower_hu_tuple = (original_bits[1], original_bits[2], original_bits[3])
    upper_hu_tuple = (original_bits[2], original_bits[3], original_bits[4])
    lower_hu_name, _, _ = BAGUA[lower_hu_tuple]
    upper_hu_name, _, _ = BAGUA[upper_hu_tuple]
    hu_key = (upper_hu_name, lower_hu_name)
    hu_info = HEXAGRAMS.get(hu_key, orig_info)

    # 爻象繪製文字
    line_symbols = []
    line_names = ["初爻", "二爻", "三爻", "四爻", "五爻", "上爻"]
    for i in range(5, -1, -1): # 由上往下排
        v = lines_val[i]
        if v == 9:
            txt = f"{line_names[i]}：⚊ 老陽 (動爻 · 變陰)"
        elif v == 6:
            txt = f"{line_names[i]}：⚋ 老陰 (動爻 · 變陽)"
        elif v == 7:
            txt = f"{line_names[i]}：⚊ 少陽 (靜爻)"
        else:
            txt = f"{line_names[i]}：⚋ 少陰 (靜爻)"
        line_symbols.append(txt)

    result = {
        "question": question,
        "timestamp": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        "original_hexagram": {
            "name": orig_info[0],
            "symbol": orig_info[1],
            "nature": f"上{upper_orig_nature}下{lower_orig_nature}",
            "attribute": orig_info[2],
            "quote": orig_info[3],
            "judgment": orig_info[4],
            "mindset": orig_info[5]
        },
        "changing_lines": changing_lines,
        "has_changes": len(changing_lines) > 0,
        "changed_hexagram": {
            "name": chg_info[0],
            "symbol": chg_info[1],
            "nature": f"上{upper_chg_name}下{lower_chg_name}",
            "attribute": chg_info[2],
            "judgment": chg_info[4]
        } if len(changing_lines) > 0 else None,
        "nuclear_hexagram": {
            "name": hu_info[0],
            "symbol": hu_info[1],
            "judgment": hu_info[4]
        },
        "lines_visual": line_symbols
    }
    return result
